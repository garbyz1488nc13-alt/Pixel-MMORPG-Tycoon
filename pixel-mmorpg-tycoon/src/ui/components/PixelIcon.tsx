export type IconName = keyof typeof ICONS;

export function PixelIcon({ name, size = 16, color = 'currentColor', accent = '#f2c14e' }: { name: IconName; size?: number; color?: string; accent?: string }) {
  const rows = ICONS[name];
  const rects: JSX.Element[] = [];
  rows.forEach((row, y) =>
    [...row].forEach((c, x) => {
      if (c === '#' || c === '+') rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={c === '+' ? accent : color} />);
    }),
  );
  return (
    <svg width={size} height={size} viewBox="0 0 8 8" shapeRendering="crispEdges" aria-hidden style={{ flexShrink: 0 }}>
      {rects}
    </svg>
  );
}
